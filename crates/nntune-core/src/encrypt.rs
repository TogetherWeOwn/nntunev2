//! Encrypt-on-write for the rclone-crypt layout that [`crate::decrypt`] reads.
//!
//! The poster encrypts each file with a fresh random 256-bit key and writes
//! the stream in the exact layout [`crate::decrypt::rclone`] expects:
//!
//! - a 32-byte header (8-byte `RCLONE\0\0` magic, then the 24-byte header
//!   nonce), followed by
//! - one 65,552-byte ciphertext block per 64 KiB plaintext block (the final
//!   block may be short): the 16-byte Poly1305 tag first, then the
//!   XSalsa20 ciphertext. The per-block nonce is the header nonce plus the
//!   little-endian block counter.
//!
//! Key custody: the file key is generated by the caller (the poster mints it
//! from the OS CSPRNG at post time) and passed in — this crate never
//! generates keys or nonces, so it keeps building for
//! `wasm32-unknown-unknown` without a `getrandom` backend. After sealing,
//! the key is wrapped in the existing AES-GCM envelope v2 by the API-side
//! mint and stored as the posted-file record's `file_key_*` columns; the
//! header nonce above is public (article 0 carries the header in the clear,
//! exactly like rclone-crypt files in the wild).
//!
//! [`Encryptor`] seals an arbitrary byte stream in `push`/`finish` order and
//! [`plan_articles`] derives the poster bookkeeping (plaintext ranges and
//! ciphertext offsets per article) from the plaintext length alone, so the
//! manifest and the NZB can be computed without re-scanning the ciphertext.

use crate::decrypt::rclone::MAGIC;
use crate::decrypt::rclone::{
    self, CIPHER_BLOCK_SIZE, CIPHER_OVERHEAD, HEADER_SIZE, PLAIN_BLOCK_SIZE,
};
use crate::{Error, Result};

/// Builds the 32-byte stream header for `header_nonce`.
///
/// Byte-identical to what the reader in [`crate::decrypt::rclone`] parses:
/// [`MAGIC`] followed by the nonce.
pub fn header(header_nonce: &[u8; 24]) -> [u8; 32] {
    let mut out = [0u8; HEADER_SIZE as usize];
    out[..MAGIC.len()].copy_from_slice(&MAGIC);
    out[MAGIC.len()..].copy_from_slice(header_nonce);
    out
}

/// Total sealed bytes (header plus cipher blocks) for `plaintext_len`
/// plaintext bytes, or `None` when the size is unrepresentable.
///
/// A short final plaintext block seals short (`remainder + 16` bytes, not a
/// full block), exactly like the files [`crate::decrypt::rclone`] reads.
pub fn ciphertext_len(plaintext_len: u64) -> Option<u64> {
    let full = plaintext_len / PLAIN_BLOCK_SIZE;
    let rem = plaintext_len % PLAIN_BLOCK_SIZE;
    let tail = if rem > 0 {
        rem.checked_add(CIPHER_OVERHEAD)?
    } else {
        0
    };
    HEADER_SIZE
        .checked_add(full.checked_mul(CIPHER_BLOCK_SIZE)?)?
        .checked_add(tail)
}

/// One article's slice of the sealed stream: which plaintext range it
/// carries and where its bytes sit in the ciphertext.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ArticleSpan {
    /// First plaintext byte in this article (inclusive).
    pub plaintext_start: u64,
    /// One past the last plaintext byte in this article.
    pub plaintext_end: u64,
    /// Byte offset of this article's first cipher byte in the sealed
    /// stream (header included, so article 0 starts at [`HEADER_SIZE`]).
    pub ciphertext_offset: u64,
    /// Cipher bytes in this article (whole cipher blocks, except the stream's
    /// final block, which seals short when the plaintext has a tail).
    pub ciphertext_len: u64,
}

/// Splits `plaintext_len` plaintext bytes into articles of at most
/// `blocks_per_article` cipher blocks each.
///
/// Article 0's offset leaves room for the 32-byte header ahead of its
/// first cipher block; article `i` holds cipher blocks
/// `[i * blocks_per_article, (i + 1) * blocks_per_article)`. Returns `None`
/// when `blocks_per_article` is zero or the geometry overflows `u64`.
/// An empty plaintext yields no spans (the poster rejects empty inputs
/// before this point).
pub fn plan_articles(plaintext_len: u64, blocks_per_article: u64) -> Option<Vec<ArticleSpan>> {
    if blocks_per_article == 0 {
        return None;
    }
    let blocks = plaintext_len.div_ceil(PLAIN_BLOCK_SIZE);
    let mut spans = Vec::new();
    let mut first_block = 0u64;
    while first_block < blocks {
        let last_block = (first_block.checked_add(blocks_per_article)?).min(blocks);
        let plaintext_start = first_block
            .checked_mul(PLAIN_BLOCK_SIZE)?
            .min(plaintext_len);
        let plaintext_end = last_block.checked_mul(PLAIN_BLOCK_SIZE)?.min(plaintext_len);
        let ciphertext_offset =
            HEADER_SIZE.checked_add(first_block.checked_mul(CIPHER_BLOCK_SIZE)?)?;
        // Only the stream's final block can be short, and it always sits in
        // the final article, so full blocks below are always full-sized.
        let plain_in_article = plaintext_end.checked_sub(plaintext_start)?;
        let full_in_article = plain_in_article / PLAIN_BLOCK_SIZE;
        let rem_in_article = plain_in_article % PLAIN_BLOCK_SIZE;
        let tail_in_article = if rem_in_article > 0 {
            rem_in_article.checked_add(CIPHER_OVERHEAD)?
        } else {
            0
        };
        let ciphertext_len = full_in_article
            .checked_mul(CIPHER_BLOCK_SIZE)?
            .checked_add(tail_in_article)?;
        spans.push(ArticleSpan {
            plaintext_start,
            plaintext_end,
            ciphertext_offset,
            ciphertext_len,
        });
        first_block = last_block;
    }
    Some(spans)
}

/// Streaming seal: feed plaintext with [`Encryptor::push`], collect the
/// [`Encryptor::finish`] tail, and prepend [`header`] before the first
/// sealed block.
pub struct Encryptor {
    key: [u8; 32],
    header_nonce: [u8; 24],
    block_number: u64,
    pending: Vec<u8>,
    plaintext_len: u64,
}

impl Encryptor {
    /// Starts a new stream. `key` is the per-file random 256-bit key and
    /// `header_nonce` its random 24-byte nonce; both come from the caller.
    pub fn new(key: [u8; 32], header_nonce: [u8; 24]) -> Self {
        Self {
            key,
            header_nonce,
            block_number: 0,
            pending: Vec::with_capacity(PLAIN_BLOCK_SIZE as usize),
            plaintext_len: 0,
        }
    }

    /// The stream header; write it before the first [`Encryptor::push`]
    /// output (article 0 carries it ahead of its first cipher block).
    pub fn header(&self) -> [u8; 32] {
        header(&self.header_nonce)
    }

    /// Plaintext bytes accepted so far.
    pub fn plaintext_len(&self) -> u64 {
        self.plaintext_len
    }

    /// Seals `chunk`, returning zero or more whole cipher blocks. Accepts
    /// any chunk size — including empty — so callers can stream reads of
    /// whatever size their IO layer produces.
    pub fn push(&mut self, chunk: &[u8]) -> Result<Vec<u8>> {
        let mut chunk = chunk;
        self.plaintext_len =
            self.plaintext_len
                .checked_add(chunk.len() as u64)
                .ok_or(Error::Bounds {
                    bound: "encrypt plaintext length",
                    limit: i64::MAX,
                })?;
        let mut out = Vec::new();
        if !self.pending.is_empty() {
            let want = (PLAIN_BLOCK_SIZE as usize) - self.pending.len();
            let take = want.min(chunk.len());
            self.pending.extend_from_slice(&chunk[..take]);
            chunk = &chunk[take..];
            if self.pending.len() == PLAIN_BLOCK_SIZE as usize {
                let block: Vec<u8> = std::mem::take(&mut self.pending);
                self.pending = Vec::with_capacity(PLAIN_BLOCK_SIZE as usize);
                out.extend_from_slice(&self.seal(&block)?);
            }
        }
        while chunk.len() >= PLAIN_BLOCK_SIZE as usize {
            let (block, rest) = chunk.split_at(PLAIN_BLOCK_SIZE as usize);
            chunk = rest;
            out.extend_from_slice(&self.seal(block)?);
        }
        self.pending.extend_from_slice(chunk);
        Ok(out)
    }

    /// Seals the buffered tail (empty when the plaintext was an exact
    /// multiple of the block size). No more plaintext may follow.
    pub fn finish(mut self) -> Result<Vec<u8>> {
        if self.pending.is_empty() {
            return Ok(Vec::new());
        }
        let tail: Vec<u8> = std::mem::take(&mut self.pending);
        self.seal(&tail)
    }

    fn seal(&mut self, plaintext: &[u8]) -> Result<Vec<u8>> {
        let mut derived = [0u8; 80];
        derived[..32].copy_from_slice(&self.key);
        let mut sealed = vec![0u8; plaintext.len() + CIPHER_OVERHEAD as usize];
        rclone::seal_block(
            &derived,
            &self.header_nonce,
            self.block_number,
            plaintext,
            &mut sealed,
        )?;
        self.block_number = self.block_number.checked_add(1).ok_or(Error::Bounds {
            bound: "encrypt block counter",
            limit: i64::MAX,
        })?;
        Ok(sealed)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::decrypt::rclone as reader;
    use sha2::{Digest, Sha256};

    /// Test-only key/nonce derivation: SHA-256 over a fixed label plus a
    /// tag. These vectors are synthetic and never touch production keys;
    /// nothing here is logged or persisted.
    fn test_key(tag: u64) -> [u8; 32] {
        let mut h = Sha256::new();
        h.update(b"nntune-core encrypt test file key v1");
        h.update(tag.to_le_bytes());
        h.finalize().into()
    }

    fn test_nonce(tag: u64) -> [u8; 24] {
        let mut h = Sha256::new();
        h.update(b"nntune-core encrypt test header nonce v1");
        h.update(tag.to_le_bytes());
        let digest = h.finalize();
        let mut nonce = [0u8; 24];
        nonce.copy_from_slice(&digest[..24]);
        nonce
    }

    fn derived_of(key: &[u8; 32]) -> [u8; 80] {
        let mut derived = [0u8; 80];
        derived[..32].copy_from_slice(key);
        derived
    }

    /// Deterministic pseudo-random bytes (xorshift64*) — no fixture files,
    /// no RNG dependency.
    fn pattern(len: usize, seed: u64) -> Vec<u8> {
        let mut state = seed | 1;
        (0..len)
            .map(|_| {
                state ^= state >> 12;
                state ^= state << 25;
                state ^= state >> 27;
                (state.wrapping_mul(0x2545F4914F6CDD1D) >> 56) as u8
            })
            .collect()
    }

    fn seal_all(plaintext: &[u8], tag: u64, chunk: usize) -> (Vec<u8>, [u8; 32]) {
        let key = test_key(tag);
        let nonce = test_nonce(tag);
        let mut enc = Encryptor::new(key, nonce);
        let mut sealed = enc.header().to_vec();
        let mut rest = plaintext;
        while !rest.is_empty() {
            let take = chunk.min(rest.len());
            sealed.extend_from_slice(&enc.push(&rest[..take]).unwrap());
            rest = &rest[take..];
        }
        sealed.extend_from_slice(&enc.finish().unwrap());
        (sealed, key)
    }

    fn read_range(sealed: &Vec<u8>, key: &[u8; 32], size: u64, off: u64, len: usize) -> Vec<u8> {
        let mut dst = vec![0u8; len];
        let n = reader::read_at(sealed, &derived_of(key), size, &mut dst, off).unwrap();
        dst.truncate(n);
        dst
    }

    #[test]
    fn header_layout_matches_reader() {
        let nonce = test_nonce(1);
        let h = header(&nonce);
        assert_eq!(&h[..8], b"RCLONE\x00\x00");
        assert_eq!(&h[8..], &nonce);
    }

    #[test]
    fn ciphertext_len_geometry() {
        assert_eq!(ciphertext_len(0), Some(HEADER_SIZE));
        // A short final block seals short: 1 plaintext byte -> 1 + 16.
        assert_eq!(ciphertext_len(1), Some(HEADER_SIZE + 1 + CIPHER_OVERHEAD));
        assert_eq!(
            ciphertext_len(PLAIN_BLOCK_SIZE),
            Some(HEADER_SIZE + CIPHER_BLOCK_SIZE)
        );
        assert_eq!(
            ciphertext_len(PLAIN_BLOCK_SIZE + 1),
            Some(HEADER_SIZE + CIPHER_BLOCK_SIZE + 1 + CIPHER_OVERHEAD)
        );
        assert_eq!(ciphertext_len(u64::MAX), None);
    }

    #[test]
    fn article_plan_matches_design_geometry() {
        // Design §4 worked example: 11 cipher blocks of 65,536 plaintext
        // bytes seal into one 721,072-byte article behind the 32-byte header.
        let spans = plan_articles(11 * PLAIN_BLOCK_SIZE, 11).unwrap();
        assert_eq!(
            spans,
            vec![ArticleSpan {
                plaintext_start: 0,
                plaintext_end: 11 * PLAIN_BLOCK_SIZE,
                ciphertext_offset: HEADER_SIZE,
                ciphertext_len: 11 * CIPHER_BLOCK_SIZE,
            }]
        );
        assert_eq!(spans[0].ciphertext_len, 721_072);

        // A twelfth block opens article 1; offsets chain without gaps. The
        // final block holds one plaintext byte, so it seals short.
        let spans = plan_articles(11 * PLAIN_BLOCK_SIZE + 1, 11).unwrap();
        assert_eq!(spans.len(), 2);
        assert_eq!(spans[1].plaintext_start, 11 * PLAIN_BLOCK_SIZE);
        assert_eq!(spans[1].plaintext_end, 11 * PLAIN_BLOCK_SIZE + 1);
        assert_eq!(
            spans[1].ciphertext_offset,
            HEADER_SIZE + 11 * CIPHER_BLOCK_SIZE
        );
        assert_eq!(spans[1].ciphertext_len, 1 + CIPHER_OVERHEAD);

        // A short final block seals short in the final article only.
        let spans = plan_articles(PLAIN_BLOCK_SIZE + 1, 11).unwrap();
        assert_eq!(spans.len(), 1);
        assert_eq!(
            spans[0].ciphertext_len,
            CIPHER_BLOCK_SIZE + 1 + CIPHER_OVERHEAD
        );
        assert_eq!(
            ciphertext_len(PLAIN_BLOCK_SIZE + 1).unwrap(),
            HEADER_SIZE + spans[0].ciphertext_len
        );

        assert_eq!(plan_articles(0, 11).unwrap(), vec![]);
        assert_eq!(plan_articles(100, 0), None);
    }

    #[test]
    fn round_trip_at_block_boundaries() {
        for &size in &[
            0u64,
            1,
            2,
            PLAIN_BLOCK_SIZE - 1,
            PLAIN_BLOCK_SIZE,
            PLAIN_BLOCK_SIZE + 1,
            2 * PLAIN_BLOCK_SIZE,
            3 * PLAIN_BLOCK_SIZE + 7,
        ] {
            let plaintext = pattern(size as usize, 0x9E3779B97F4A7C15);
            for &chunk in &[1usize, 7, 100_000] {
                let (sealed, key) = seal_all(&plaintext, size, chunk);
                assert_eq!(sealed.len() as u64, ciphertext_len(size).unwrap());
                let back = read_range(&sealed, &key, size, 0, size as usize + 16);
                assert_eq!(back, plaintext, "size {size} chunk {chunk}");
            }
        }
    }

    #[test]
    fn range_reads_span_block_edges() {
        let size = 3 * PLAIN_BLOCK_SIZE + 7;
        let plaintext = pattern(size as usize, 42);
        let (sealed, key) = seal_all(&plaintext, 99, 65_537);
        // Windows straddling each block edge, plus unaligned tails.
        let mut offs = vec![0, 1, size - 1];
        for edge in [PLAIN_BLOCK_SIZE, 2 * PLAIN_BLOCK_SIZE, 3 * PLAIN_BLOCK_SIZE] {
            for delta in [-2i64, -1, 0, 1, 2] {
                let off = (edge as i64 + delta) as u64;
                if off < size {
                    offs.push(off);
                }
            }
        }
        for off in offs {
            for len in [1usize, 16, 65_552, 200_000] {
                let want_end = (off + len as u64).min(size);
                let want = &plaintext[off as usize..want_end as usize];
                let got = read_range(&sealed, &key, size, off, len);
                assert_eq!(got, want, "off {off} len {len}");
            }
        }
    }

    #[test]
    fn tampered_ciphertext_fails_authentication() {
        let plaintext = pattern(70_000, 7);
        let (mut sealed, key) = seal_all(&plaintext, 5, 8192);
        // Flip a byte inside the first cipher block's Poly1305 tag.
        sealed[HEADER_SIZE as usize] ^= 0x01;
        let mut dst = vec![0u8; 64];
        let err = reader::read_at(&sealed, &derived_of(&key), 70_000, &mut dst, 0)
            .expect_err("tampered tag must fail");
        assert!(matches!(err, Error::Decrypt(_)));
    }

    #[test]
    fn wrong_key_fails_authentication() {
        let plaintext = pattern(100, 8);
        let (sealed, _) = seal_all(&plaintext, 8, 64);
        let mut dst = vec![0u8; 100];
        reader::read_at(&sealed, &derived_of(&test_key(9)), 100, &mut dst, 0)
            .expect_err("wrong key must fail");
    }
}
