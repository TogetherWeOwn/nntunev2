//! Acceptance: meter signals on terminal play failures.
//!
//! Test-first contract for the paired build slice "stream: emit meter
//! signals on terminal play failures", following the pattern of
//! `grant_rejection_meter_signal.rs`. Terminal `ArticleMissing` (`430`)
//! and `Decode` failures — the two most common user-visible play failures
//! — currently leave zero meter footprint: no event, nothing for a
//! dashboard to group by.
//!
//! This file is intentionally RED on the source head by *assertion*, not
//! by compile error: it names no not-yet-existing variant. Instead it
//! identifies the new events through the existing public
//! `meter::kind_slug()`, so the target builds today and each RED test
//! fails on "exactly one event with slug X, got [...]" until the builder
//! lands the fix. Every other suite stays green.
//!
//! ## Contract the builder implements (do NOT edit this file to match
//! code; change the code to match this file)
//!
//! In `meter.rs`:
//! - Two new distinct `MeterKind` variants (variant names are the
//!   builder's choice, e.g. `ArticleMissing` / `DecodeFailed`) whose
//!   `kind_slug()` values are exactly `"article_missing"` and
//!   `"decode_failed"`. The two kinds must differ from each other and
//!   from every pre-existing kind; the two slugs must differ from each
//!   other and from every pre-existing slug, so Analytics Engine points
//!   (`analytics_point`, blobs `[kind, user_id, track_id]`) are
//!   dashboard-groupable by failure reason. Extend meter.rs's own
//!   distinct-slug unit test to cover the new kinds.
//! - `MeterEvent` shape for terminal failures, mirroring the grant
//!   rejections: `track_id` is the requested track, `user_id` is the
//!   granted user (`user-1` in these fixtures), `bytes == 0`,
//!   `seconds == 0`. The event — and its `Debug` — must never contain
//!   token or secret material.
//!
//! Emission points in the play path (`play.rs`):
//! - A play that terminates with `PlayError::ArticleMissing` emits
//!   exactly one `"article_missing"` event; a play that terminates with
//!   `PlayError::Decode` emits exactly one `"decode_failed"` event. One
//!   event per terminal play — a second identical failure emits a
//!   second event (no once-ever suppression).
//! - "Terminates" covers both surfaces: `play()` itself returning the
//!   error (first segment gone/corrupt) and a started stream whose
//!   `error()` is that failure and whose `finalize` returns it (later
//!   segment gone/corrupt). Either way the play the user asked for
//!   failed, and either way exactly one event lands.
//! - A terminal failure emits its single event and nothing else new: no
//!   `ProviderError`, no `QuarantineEntered`/`QuarantineExited`, no
//!   `WarmRedial`, no `GrantRejected*`. Grant and quarantine signals are
//!   unchanged. The pool never quarantines, no lease is held
//!   (`pool.in_use() == 0`), and nothing partial is cached.
//! - Non-terminal failures stay silent: a fully-served `206` whose
//!   *post-range cache fill* hits a gone article finalizes `Ok` (see
//!   `fill_settle.rs`) and emits neither new slug — the user-visible
//!   play succeeded. A successful play likewise emits neither slug,
//!   with normal metering (`BytesServed`) intact.

