#[test]
fn terminal_failures_emit_distinct_kinds_with_distinct_slugs() {
    let (_, segs_gone, _) = fixture_track("gone", 20_000, 10_000);
    let (_, segs_corrupt, mut arts_corrupt) = fixture_track("corrupt", 20_000, 10_000);
    arts_corrupt.insert(segs_corrupt[0].clone(), b"this is not yEnc\r\n".to_vec());
    let server = FakeNntp::start(arts_corrupt);

    // Run each terminal failure against its own meter and collect the one
    // new kind it emits (the kind whose slug is new, i.e. not produced by
    // any pre-existing kind).
    let mut found: Vec<(MeterKind, &'static str)> = Vec::new();
    for (track, segs) in [("track-gone", &segs_gone), ("track-corrupt", &segs_corrupt)] {
        let mut pool: StreamPool = Pool::new(4);
        let mut cache = ContentCache::new();
        let mut meter = MemoryMeter::default();
        let token = grant_for(track);
        let inp = input(&token, track, None, &server, segs);
        assert!(
            play(&mut pool, &mut cache, &mut meter, SECRET, &inp).is_err(),
            "terminal fixture for {track} must fail"
        );
        let new_kinds: Vec<MeterKind> = meter
            .events
            .iter()
            .map(|e| e.kind)
            .filter(|k| !PREEXISTING_KINDS.contains(k))
            .collect();
        assert_eq!(
            new_kinds.len(),
            1,
            "{track}: exactly one event of a new kind, got slugs {:?}",
            slugs_of(&meter)
        );
        found.push((new_kinds[0], kind_slug(new_kinds[0])));
    }

    assert_ne!(
        found[0].0, found[1].0,
        "missing and decode must be distinct kinds"
    );
    assert_ne!(
        found[0].1, found[1].1,
        "missing and decode must have distinct slugs"
    );
    let mut slugs: Vec<&str> = found.iter().map(|(_, slug)| *slug).collect();
    slugs.sort_unstable();
    assert_eq!(
        slugs,
        [ARTICLE_MISSING_SLUG, DECODE_FAILED_SLUG],
        "the two terminal slugs are exactly article_missing / decode_failed"
    );
}

/// Green control: a successful play emits neither terminal slug, and its
/// normal metering is untouched.
#[test]
fn successful_play_emits_no_terminal_failure_signal() {
    let (plain, segments, articles) = fixture_track("ok", 20_000, 10_000);
    let server = FakeNntp::start(articles);
    let mut pool: StreamPool = Pool::new(4);
    let mut cache = ContentCache::new();
    let mut meter = MemoryMeter::default();

    let token = grant_for("track-ok");
    let inp = input(&token, "track-ok", None, &server, &segments);
    let resp = play(&mut pool, &mut cache, &mut meter, SECRET, &inp).expect("healthy play");
    let (body, stream) = drain_to_vec(resp.stream);
    assert_eq!(body, plain);
    stream
        .finalize(&mut pool, &mut cache, &mut meter)
        .expect("finalize");

    for slug in [ARTICLE_MISSING_SLUG, DECODE_FAILED_SLUG] {
        assert!(
            events_with_slug(&meter, slug).is_empty(),
            "a successful play must not emit {slug}; got slugs {:?}",
            slugs_of(&meter)
        );
    }
    let served: u64 = meter
        .events
        .iter()
        .filter(|e| e.kind == MeterKind::BytesServed && e.track_id == "track-ok")
        .map(|e| e.bytes)
        .sum();
    assert_eq!(
        served as usize,
        plain.len(),
        "normal metering for the successful play is intact"
    );
}

/// Green control: a fully-served `206` whose post-range cache fill hits a
/// gone article is NOT a terminal failure — `finalize` stays `Ok` (see
/// `fill_settle.rs`) and neither terminal slug is emitted. The build must
/// not widen "terminal" to background fill work.
#[test]
fn served_206_fill_missing_article_is_not_a_terminal_failure() {
    let (plain, segments, mut articles) = fixture_track("fill-missing", 60_000, 20_000);
    assert_eq!(segments.len(), 3);
    // Segment 1 is gone; serving bytes 0-99 never needs it, the fill does.
    articles.remove(&segments[1]);
    let server = FakeNntp::start(articles);
    let mut pool: StreamPool = Pool::new(4);
    let mut cache = ContentCache::new();
    let mut meter = MemoryMeter::default();

    let token = grant_for("track-fill-missing");
    let inp = input(
        &token,
        "track-fill-missing",
        Some("bytes=0-99"),
        &server,
        &segments,
    );
    let resp = play(&mut pool, &mut cache, &mut meter, SECRET, &inp).expect("play must start");
    assert_eq!(resp.status, 206);
    let (body, stream) = drain_to_vec(resp.stream);
    assert_eq!(body, &plain[..100], "client got its full range");
    assert!(
        stream.error().is_none(),
        "serving completed without error; got {:?}",
        stream.error()
    );
    assert_eq!(server.bodies(), 1, "fill has not run yet");

    let result = stream.finalize(&mut pool, &mut cache, &mut meter);
    assert!(server.bodies() >= 2, "finalize must attempt the fill");
    assert_eq!(
        result,
        Ok(()),
        "a fill-phase missing article must not fail a fully-served play"
    );
    for slug in [ARTICLE_MISSING_SLUG, DECODE_FAILED_SLUG] {
        assert!(
            events_with_slug(&meter, slug).is_empty(),
            "a non-terminal fill failure must not emit {slug}; got slugs {:?}",
            slugs_of(&meter)
        );
    }
    assert!(!pool.quarantined());
    assert_eq!(pool.in_use(), 0, "the lease is returned");
}
