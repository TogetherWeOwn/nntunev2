const SECRET: &[u8] = b"play-terminal-acceptance-secret";
const NOW_UNIX: u64 = 1_700_000_000;
/// Within the 900s grant TTL cap.
const EXP_UNIX: u64 = NOW_UNIX + 900;
const CIPHER_KEY: u8 = 0x5A;

/// The exact Analytics Engine slugs the paired build must land.
const ARTICLE_MISSING_SLUG: &str = "article_missing";
const DECODE_FAILED_SLUG: &str = "decode_failed";

/// Every kind that exists before the paired build. The terminal-failure
/// kinds must be new: distinct from all of these, not a reused slug on an
/// old kind.
const PREEXISTING_KINDS: [MeterKind; 13] = [
    MeterKind::PlayStart,
    MeterKind::CacheHit,
    MeterKind::CacheMiss,
    MeterKind::BytesServed,
    MeterKind::PrefetchEnqueued,
    MeterKind::ProviderError,
    MeterKind::GrantRejectedExpired,
    MeterKind::GrantRejectedExcessiveExpiry,
    MeterKind::GrantRejectedWrongTrack,
    MeterKind::QuarantineEntered,
    MeterKind::QuarantineExited,
    MeterKind::WarmRedial,
    MeterKind::ReconcileMismatch,
];

type Fixture = (Vec<u8>, Vec<String>, HashMap<String, Vec<u8>>);

/// Deterministic pseudo-audio covering every byte value (exercises yEnc
/// escapes), posted the way Usenet does it: one yEnc *multipart* article
/// per `seg_len` bytes. Same fixture shape as `stream_integration.rs`.
fn fixture_track(tag: &str, len: usize, seg_len: usize) -> Fixture {
    let mut plain = Vec::with_capacity(len);
    for i in 0..len {
        plain.push(((i * 7919 + tag.len()) % 256) as u8);
    }
    let ciphered: Vec<u8> = plain.iter().map(|b| b ^ CIPHER_KEY).collect();
    let file_crc = yenc::crc32(&ciphered);
    let total = ciphered.len().div_ceil(seg_len) as u32;
    let mut articles = HashMap::new();
    let mut segments = Vec::new();
    for (i, chunk) in ciphered.chunks(seg_len).enumerate() {
        let part = i as u32 + 1;
        let mid = format!("{tag}-seg{i}@synthetic.test");
        let text = yenc::encode_part(
            chunk,
            &format!("{tag}.flac"),
            PartSpec {
                file_size: len as u64,
                part,
                total,
                offset: (i * seg_len) as u64,
                file_crc: (part == total).then_some(file_crc),
            },
        );
        articles.insert(mid.clone(), text);
        segments.push(mid);
    }
    (plain, segments, articles)
}

/// Minimal NNTP server: greeting + `BODY <mid>` with dot-stuffing, `430`
/// for unknown articles.
struct FakeNntp {
    addr: SocketAddr,
    stop: Arc<AtomicBool>,
    bodies: Arc<AtomicUsize>,
    handle: Option<thread::JoinHandle<()>>,
}

impl FakeNntp {
    fn start(articles: HashMap<String, Vec<u8>>) -> Self {
        let listener = TcpListener::bind("127.0.0.1:0").expect("bind fake NNTP");
        let addr = listener.local_addr().expect("local addr");
        listener.set_nonblocking(true).expect("nonblocking");
        let stop = Arc::new(AtomicBool::new(false));
        let bodies = Arc::new(AtomicUsize::new(0));
        let (stop_c, bodies_c) = (Arc::clone(&stop), Arc::clone(&bodies));
        let handle = thread::spawn(move || {
            while !stop_c.load(Ordering::SeqCst) {
                let (stream, _) = match listener.accept() {
                    Ok(pair) => pair,
                    Err(e) if e.kind() == std::io::ErrorKind::WouldBlock => {
                        thread::sleep(Duration::from_millis(5));
                        continue;
                    }
                    Err(_) => break,
                };
                Self::serve(stream, &articles, &bodies_c);
            }
        });
        Self {
            addr,
            stop,
            bodies,
            handle: Some(handle),
        }
    }

    fn serve(stream: TcpStream, articles: &HashMap<String, Vec<u8>>, bodies: &AtomicUsize) {
        let _ = stream.set_read_timeout(Some(Duration::from_secs(2)));
        let mut reader = BufReader::new(stream.try_clone().expect("clone conn"));
        let mut writer = stream;
        let _ = writer.write_all(b"200 synthetic NNTP ready\r\n");
        let mut line = Vec::new();
        loop {
            line.clear();
            match reader.read_until(b'\n', &mut line) {
                Ok(0) => break,
                Ok(_) => {}
                Err(_) => break,
            }
            while line.last() == Some(&b'\n') || line.last() == Some(&b'\r') {
                line.pop();
            }
            let cmd = String::from_utf8_lossy(&line).into_owned();
            if let Some(mid) = cmd
                .strip_prefix("BODY ")
                .map(|s| s.trim().trim_matches(|c| c == '<' || c == '>'))
            {
                bodies.fetch_add(1, Ordering::SeqCst);
                let full_mid = format!("<{mid}>");
                match articles.get(mid) {
                    Some(article) => {
                        let _ =
                            writer.write_all(format!("222 0 {full_mid} follows\r\n").as_bytes());
                        for raw_line in article.split(|&b| b == b'\n') {
                            let text_line = raw_line.strip_suffix(b"\r").unwrap_or(raw_line);
                            // Dot-stuff per RFC 3977 §3.1.
                            if text_line.first() == Some(&b'.') {
                                let _ = writer.write_all(b".");
                            }
                            let _ = writer.write_all(text_line);
                            let _ = writer.write_all(b"\r\n");
                        }
                        let _ = writer.write_all(b".\r\n");
                    }
                    None => {
                        let _ = writer.write_all(b"430 no such article\r\n");
                    }
                }
            } else if cmd == "QUIT" {
                let _ = writer.write_all(b"205 bye\r\n");
                break;
            } else {
                let _ = writer.write_all(b"500 unknown command\r\n");
            }
        }
    }

    /// BODY commands received so far.
    fn bodies(&self) -> usize {
        self.bodies.load(Ordering::SeqCst)
    }
}

impl Drop for FakeNntp {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::SeqCst);
        // Wake the accept loop promptly.
        let _ = TcpStream::connect(self.addr);
        if let Some(handle) = self.handle.take() {
            let _ = handle.join();
        }
    }
}

fn drain_to_vec(mut stream: PlayStream) -> (Vec<u8>, PlayStream) {
    let mut body = Vec::new();
    for chunk in stream.by_ref() {
        body.extend_from_slice(&chunk);
    }
    (body, stream)
}

fn input<'a>(
    token: &'a str,
    track_id: &'a str,
    range: Option<&'a str>,
    server: &FakeNntp,
    segments: &'a [String],
) -> PlayInput<'a> {
    PlayInput {
        trace_id: None,
        token,
        track_id,
        range,
        server_addr: server.addr,
        segments,
        segment_ranges: None,
        cipher_key: CIPHER_KEY,
        now_unix: NOW_UNIX,
        up_next: None,
    }
}

fn grant_for(track: &str) -> String {
    grant::issue("user-1", track, EXP_UNIX, SECRET)
}

/// Events carrying a given slug, identified through the public
/// `kind_slug()` so this file compiles before the new kinds exist.
fn events_with_slug<'a>(meter: &'a MemoryMeter, slug: &str) -> Vec<&'a MeterEvent> {
    meter
        .events
        .iter()
        .filter(|e| kind_slug(e.kind) == slug)
        .collect()
}

fn slugs_of(meter: &MemoryMeter) -> Vec<&'static str> {
    meter.events.iter().map(|e| kind_slug(e.kind)).collect()
}

/// The terminal-failure shape: requested track, granted user, no bytes or
/// seconds, dashboard-groupable, and no secret or token material anywhere
/// in the event's `Debug`.
fn assert_terminal_shape(event: &MeterEvent, slug: &str, expected_track: &str, token: &str) {
    assert!(
        !PREEXISTING_KINDS.contains(&event.kind),
        "{slug}: terminal event must use a new kind, got pre-existing {:?}",
        event.kind
    );
    assert_eq!(
        event.track_id, expected_track,
        "{slug}: event must carry the requested track"
    );
    assert_eq!(
        event.user_id, "user-1",
        "{slug}: event must carry the granted user"
    );
    assert_eq!(event.bytes, 0, "{slug}: terminal events serve no bytes");
    assert_eq!(
        event.seconds, 0,
        "{slug}: terminal events attribute no stream seconds"
    );
    let debug = format!("{event:?} {:?}", event.kind);
    assert!(
        !debug.contains(token),
        "{slug}: event must not contain token material"
    );
    let secret = String::from_utf8_lossy(SECRET);
    assert!(
        !debug.contains(secret.as_ref()),
        "{slug}: event must not contain secret material"
    );
    // Dashboard-groupable: the Analytics Engine point groups by the slug,
    // indexed by user, carrying the track, with zero magnitudes.
    let point = analytics_point(event);
    assert_eq!(point.blobs[0], slug, "{slug}: AE blob 0 is the kind slug");
    assert_eq!(point.index, "user-1", "{slug}: AE index is the user");
    assert_eq!(
        point.blobs[2], expected_track,
        "{slug}: AE blob 2 is the track"
    );
    assert_eq!(point.doubles, [0.0, 0.0], "{slug}: AE doubles are zero");
}

/// Terminal missing/decode failures are meter-only signals on top of the
/// existing failure: no provider/quarantine/grant noise, no quarantine,
/// no lease held, nothing partial cached.
fn assert_no_terminal_side_effects(
    meter: &MemoryMeter,
    pool: &StreamPool,
    cache: &ContentCache,
    track: &str,
    case: &str,
) {
    for kind in [
        MeterKind::ProviderError,
        MeterKind::QuarantineEntered,
        MeterKind::QuarantineExited,
        MeterKind::WarmRedial,
        MeterKind::GrantRejectedExpired,
        MeterKind::GrantRejectedExcessiveExpiry,
        MeterKind::GrantRejectedWrongTrack,
    ] {
        assert!(
            !meter.has_kind(kind),
            "{case}: terminal content failure must not emit {kind:?}; got slugs {:?}",
            slugs_of(meter)
        );
    }
    assert!(
        !pool.quarantined(),
        "{case}: a content failure says nothing about the provider"
    );
    assert_eq!(pool.in_use(), 0, "{case}: failed plays hold no lease");
    assert!(
        cache.get_track(track).is_none(),
        "{case}: failed plays cache nothing partial"
    );
}

#[test]
fn missing_first_segment_terminal_failure_emits_article_missing() {
    let (_, segs_gone, _) = fixture_track("gone", 20_000, 10_000);
    // "gone" articles are absent from the server: 430 on the first BODY.
    let server = FakeNntp::start(HashMap::new());
    let mut pool: StreamPool = Pool::new(4);
    let mut cache = ContentCache::new();
    let mut meter = MemoryMeter::default();

    // Two identical terminal plays: exactly one event per play, never
    // suppressed after the first.
    for attempt in 1..=2usize {
        let token = grant_for("track-gone");
        let inp = input(&token, "track-gone", None, &server, &segs_gone);
        assert!(
            matches!(
                play(&mut pool, &mut cache, &mut meter, SECRET, &inp),
                Err(PlayError::ArticleMissing(_))
            ),
            "gone first segment must be ArticleMissing"
        );
        let missing = events_with_slug(&meter, ARTICLE_MISSING_SLUG);
        assert_eq!(
            missing.len(),
            attempt,
            "exactly one article_missing event per terminal play, got slugs {:?}",
            slugs_of(&meter)
        );
        assert_terminal_shape(
            missing[attempt - 1],
            ARTICLE_MISSING_SLUG,
            "track-gone",
            &token,
        );
        assert!(
            events_with_slug(&meter, DECODE_FAILED_SLUG).is_empty(),
            "a missing article is not a decode failure; got slugs {:?}",
            slugs_of(&meter)
        );
    }
    assert!(
        !meter.has_kind(MeterKind::BytesServed),
        "a play that never started serving meters no bytes; got slugs {:?}",
        slugs_of(&meter)
    );
    assert_no_terminal_side_effects(&meter, &pool, &cache, "track-gone", "missing-first");
}

