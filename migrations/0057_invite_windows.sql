-- Member invite windows (post-M1 storage only). Timestamps are Unix seconds,
-- like invite_codes.expires_at. Admin invites never participate in a window.
SET search_path = public, pg_catalog;

CREATE TABLE IF NOT EXISTS public.invite_windows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    starts_at BIGINT NOT NULL,
    ends_at BIGINT NOT NULL,
    created_by TEXT REFERENCES public.users (id) ON DELETE SET NULL,
    note TEXT,
    -- Shorten by reducing ends_at. For cancellation or closure at the start,
    -- set ends_at = starts_at: the retained row has an empty range.
    CONSTRAINT invite_windows_time_order CHECK (starts_at <= ends_at),
    CONSTRAINT invite_windows_no_overlap
        EXCLUDE USING gist (int8range(starts_at, ends_at, '[)') WITH &&)
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_catalog.pg_constraint
        WHERE conrelid = 'public.invite_codes'::regclass
          AND conname = 'invite_codes_window_kind_check'
    ) THEN
        ALTER TABLE public.invite_codes
            ADD CONSTRAINT invite_codes_window_kind_check CHECK (
                (kind = 'admin' AND window_id IS NULL)
                OR (kind = 'member' AND window_id IS NOT NULL)
            );
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_catalog.pg_constraint
        WHERE conrelid = 'public.invite_codes'::regclass
          AND conname = 'invite_codes_window_fk'
    ) THEN
        -- Preserve the ledger's window attribution; closing is not deletion.
        ALTER TABLE public.invite_codes ADD CONSTRAINT invite_codes_window_fk
            FOREIGN KEY (window_id) REFERENCES public.invite_windows (id);
    END IF;
END $$;

-- Count all issued rows for a window and issuer, regardless of invite state.
CREATE INDEX IF NOT EXISTS idx_invite_codes_window_issuer
    ON public.invite_codes (window_id, issued_by) WHERE window_id IS NOT NULL;
