-- Admin-issued invites: extend `invite_codes` from the optional
-- hash-only gate (migration 0002) into the audited invite ledger the
-- admin API issues, lists and revokes through.
--
-- A surrogate `id` becomes the primary key so audit rows can reference
-- an invite by row id; `code_hash` stays unique and is still the only
-- code material at rest (plaintext is shown to the issuer once, never
-- stored or logged). Redeemed codes are retained for the audit trail,
-- and spend state keys on `redeemed_at` (with the legacy `used` flag
-- kept in sync by the claim): the user FKs are `ON DELETE SET NULL`,
-- so deleting an account unlinks it without ever freeing its code.
--
-- `expires_at` is required going forward. Rows that predate this
-- migration were operator-seeded codes with no expiry; they are
-- backfilled to `created_at + 7 days` (the seeded
-- `invite_default_expiry_days`), which retires any still-unredeemed
-- legacy code instead of leaving it valid forever.
--
-- `window_id` has no FK yet: the `invite_windows` table lands with
-- member invites (post-M1); admin invites always store NULL.
--
-- Replay-safe: every statement is idempotent, so re-applying this
-- file changes nothing.

ALTER TABLE invite_codes ADD COLUMN IF NOT EXISTS id BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE invite_codes ADD COLUMN IF NOT EXISTS issued_by TEXT REFERENCES users (id) ON DELETE SET NULL;
ALTER TABLE invite_codes ADD COLUMN IF NOT EXISTS kind TEXT NOT NULL DEFAULT 'admin';
ALTER TABLE invite_codes ADD COLUMN IF NOT EXISTS email TEXT;
ALTER TABLE invite_codes ADD COLUMN IF NOT EXISTS expires_at BIGINT;
ALTER TABLE invite_codes ADD COLUMN IF NOT EXISTS redeemed_by TEXT REFERENCES users (id) ON DELETE SET NULL;
ALTER TABLE invite_codes ADD COLUMN IF NOT EXISTS redeemed_at BIGINT;
ALTER TABLE invite_codes ADD COLUMN IF NOT EXISTS revoked_at BIGINT;
ALTER TABLE invite_codes ADD COLUMN IF NOT EXISTS revoked_by TEXT REFERENCES users (id) ON DELETE SET NULL;
ALTER TABLE invite_codes ADD COLUMN IF NOT EXISTS window_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'invite_codes_kind_check'
          AND conrelid = 'invite_codes'::regclass
    ) THEN
        ALTER TABLE invite_codes
            ADD CONSTRAINT invite_codes_kind_check CHECK (kind IN ('admin', 'member'));
    END IF;
END $$;

-- Legacy spend state: a pre-0029 row with `used = TRUE` was redeemed
-- at some unknown instant. Stamp `redeemed_at` with its creation time
-- so the spend predicates (which key on `redeemed_at`) keep it spent
-- forever, then give every row its required expiry.
UPDATE invite_codes SET redeemed_at = created_at WHERE used AND redeemed_at IS NULL;
UPDATE invite_codes SET expires_at = created_at + 604800 WHERE expires_at IS NULL;
ALTER TABLE invite_codes ALTER COLUMN expires_at SET NOT NULL;

-- Swap the primary key from `code_hash` to the surrogate `id` (once).
DO $$
DECLARE
    pk_cols TEXT;
BEGIN
    SELECT string_agg(a.attname, ',' ORDER BY a.attname) INTO pk_cols
    FROM pg_index i
    JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY (i.indkey)
    WHERE i.indrelid = 'invite_codes'::regclass AND i.indisprimary;
    IF pk_cols = 'code_hash' THEN
        ALTER TABLE invite_codes DROP CONSTRAINT invite_codes_pkey;
        ALTER TABLE invite_codes ADD PRIMARY KEY (id);
    END IF;
END $$;
ALTER TABLE invite_codes ALTER COLUMN code_hash SET NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS invite_codes_code_hash_key ON invite_codes (code_hash);
CREATE INDEX IF NOT EXISTS idx_invite_codes_issued_by ON invite_codes (issued_by);

-- The invite tree, on the account it created: survives any later
-- cleanup of the code table. SET NULL on issuer deletion, like the
-- code-side FKs above.
ALTER TABLE users ADD COLUMN IF NOT EXISTS invited_by TEXT REFERENCES users (id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_users_invited_by ON users (invited_by);
